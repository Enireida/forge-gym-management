package com.unyt.gym.service;

import com.unyt.gym.entity.Member;
import com.unyt.gym.entity.Notification;
import com.unyt.gym.entity.Notification.NotifType;
import com.unyt.gym.repository.MemberRepository;
import com.unyt.gym.repository.NotificationRepository;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;

import java.time.LocalDate;
import java.time.temporal.ChronoUnit;
import java.util.List;

/**
 * Central place that creates in-app notifications.
 *
 * <p>Two sources feed the notification center:
 * <ul>
 *   <li><b>Automatic</b> – generated by system events (membership expiry, class
 *       booking/cancellation, waitlist openings, goal completion).</li>
 *   <li><b>Manual</b> – staff broadcast a message to one or all members.</li>
 * </ul>
 */
@Service
public class NotificationService {

    private static final Logger log = LoggerFactory.getLogger(NotificationService.class);

    private final NotificationRepository notifRepo;
    private final MemberRepository memberRepo;

    public NotificationService(NotificationRepository notifRepo, MemberRepository memberRepo) {
        this.notifRepo  = notifRepo;
        this.memberRepo = memberRepo;
    }

    /** Send a single notification to one member, unless they opted out of this type. */
    public void notify(Member member, NotifType type, String title, String message, String linkUrl) {
        if (member == null) return;
        if (member.isNotifTypeDisabled(type.name())) return;
        notifRepo.save(new Notification(member, type, title, message, linkUrl));
    }

    /** Broadcast a manual message to a single member. */
    public void sendToMember(Member member, String title, String message) {
        notify(member, NotifType.ANNOUNCEMENT, title, message, null);
    }

    /** Broadcast a manual message to every member. Returns how many were notified. */
    public int sendToAllMembers(String title, String message) {
        List<Member> all = memberRepo.findAll();
        for (Member m : all) {
            notifRepo.save(new Notification(m, NotifType.ANNOUNCEMENT, title, message, null));
        }
        log.info("Manual notification broadcast to {} members: {}", all.size(), title);
        return all.size();
    }

    /**
     * Creates a "membership expiring soon" reminder when the member's plan ends
     * within 7 days. Guards against duplicates: only one unread expiry reminder
     * exists at a time. Safe to call on every dashboard load.
     */
    public void checkMembershipExpiry(Member member) {
        if (member == null || member.getExpiryDate() == null) return;
        long days = ChronoUnit.DAYS.between(LocalDate.now(), member.getExpiryDate());
        if (days < 0 || days > 7) return;
        if (notifRepo.existsByMemberIdAndTypeAndReadFalse(member.getId(), NotifType.MEMBERSHIP_EXPIRY)) return;

        String when = days == 0 ? "today" : ("in " + days + " day" + (days == 1 ? "" : "s"));
        notify(member, NotifType.MEMBERSHIP_EXPIRY,
                "Membership expiring soon",
                "Your membership expires " + when + " (on " + member.getExpiryDate()
                        + "). Renew to keep your gym access.",
                "/client/membership");
    }
}
